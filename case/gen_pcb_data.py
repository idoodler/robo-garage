# Generate pcb_data.scad for the case from the PCB single source of truth (parts.py).
# KiCad coords (y down) -> SCAD coords (y up): y_s = H - y_k.
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'pcb', 'gen'))
import parts  # noqa: E402

H = parts.H
WAGO_H = 14.5          # WAGO 804 body height above the PCB (v1.1)
KF_H = 11.7            # Kefa KF250-3.5 body height above the PCB (v1.2)


def ys(y):
    return round(H - y, 3)


def wago_box(ref):
    """Clamp body in KiCad coords from pin 1 and rotation (+fy = wire entry side).
    WAGO 804-10n: local fx in [-2.75, 5(n-1)+3.75], fy in [-8.3, 6.7], 14.5 high.
    Kefa KF250-3.5-nP (v1.2): fx in [-2.55, 3.5(n-1)+2.55], fy in [-5.0, 7.0], 11.7 high."""
    p = parts.P[ref]
    if p['fp'].startswith('KF250-3.5-'):
        n = int(p['fp'].split('-')[2][0])
        fx0, fx1, fy0, fy1, h = -2.55, 3.5 * (n - 1) + 2.55, -5.0, 7.0, KF_H
    else:
        n = int(p['fp'].split('_1x0')[1][0])
        fx0, fx1, fy0, fy1, h = -2.75, 5 * (n - 1) + 3.75, -8.3, 6.7, WAGO_H
    x, y, r = p['x'], p['y'], p['rot'] % 360
    if r == 0:
        xa, xb, ya, yb = x + fx0, x + fx1, y + fy0, y + fy1
    elif r == 90:      # (dx, dy) = (fy, -fx)
        xa, xb, ya, yb = x + fy0, x + fy1, y - fx1, y - fx0
    elif r == 270:     # (dx, dy) = (-fy, fx)
        xa, xb, ya, yb = x - fy1, x - fy0, y + fx0, y + fx1
    else:
        raise SystemExit('rotation %s' % r)
    return [round(xa, 3), ys(yb), round(xb, 3), ys(ya), h]


def pos(ref):
    p = parts.P[ref]
    return [p['x'], ys(p['y'])]


refs = ['J2', 'J5', 'J7', 'J10', 'J8', 'J9', 'J12', 'J13', 'J14']
lines = ['// generated by gen_pcb_data.py from parts.py (PCB v%s) - SCAD coords, y up' % parts.VERSION,
         'holes = %s;' % [pos('H%d' % i) for i in (3, 2, 1, 4)],
         'wago = %s;  // %s' % ([wago_box(r) for r in refs], ','.join(refs))]
for name, ref in [('led1', 'LED1'), ('c1_pos', 'C1'), ('c3_pos', 'C3'), ('c13_pos', 'C13'), ('l1_pos', 'L1'),
                  ('u4_pos', 'U4'), ('u1_pos', 'U1'), ('j6_pos', 'J6'), ('u5_pos', 'U5'), ('c28_pos', 'C28'),
                  ('bz_pos', 'BZ1')]:
    lines.append('%s = %s;' % (name, pos(ref)))
x0, y0, x1, y1 = parts.ISL
w = parts.SLOT_W
# v1.2: DevKitC rotated, USB-C at the left board edge. [usb face x, antenna end x, y centre wide board, y centre narrow]
lines.append('devkit = %s;  // USB-C face x, antenna end x, USB-C centre y (25.4 mm board / 22.86 mm board)' % [
    round(parts.DK_X0 - 2.68, 2), round(parts.DK_X0 + 18 * 2.54 + 1.27 + 6.16, 2),
    round(ys(parts.DK_Y0 + parts.ROW_WIDE / 2), 2), round(ys(parts.DK_Y0 + parts.ROW_NARROW / 2), 2)])
lines.append('slot_outer = %s;  // C-slot around the SHT40 island [x0, y0, x1, y1]' % [x0 - w, ys(y1 + w), x1 + w, ys(y0 - w)])
cx0, cy0, cx1, cy1 = parts.CHAMBER
lines.append('chamber = %s;  // sensor chamber: partitions at x0 and y1' % [cx0, ys(cy1), cx1, ys(cy0)])
open(os.path.join(HERE, 'pcb_data.scad'), 'w').write('\n'.join(lines) + '\n')
print('\n'.join(lines))
